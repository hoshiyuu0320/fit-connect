/// 担当トレーナーの表示名（全画面で共通）。
///
/// `trainers.name` は名前そのもの（例: 「田中」）。画面ごとにばらつかないよう、
/// 名前の組み立てはこの関数1箇所にだけ置く。
///
/// - 前後の空白は除く
/// - null・空白のみ → 「トレーナー」
/// - すでに末尾が「トレーナー」ならそのまま（「田中トレーナー」→「田中トレーナー」）
/// - それ以外は「{名前}トレーナー」（「田中」→「田中トレーナー」、「田中 太郎」→「田中 太郎トレーナー」）
///
/// 「田中トレーナーのメモ」「田中トレーナーに返信」のように助詞が続く文言でも、
/// 呼び出し側は「トレーナー」を足さずに、この戻り値へそのまま続ける。
/// 「あなたの担当トレーナー」のような固定文言は、この関数を通さない。
String trainerDisplayName(String? name) {
  final trimmed = name?.trim() ?? '';
  if (trimmed.isEmpty) return 'トレーナー';
  return trimmed.endsWith('トレーナー') ? trimmed : '$trimmedトレーナー';
}
